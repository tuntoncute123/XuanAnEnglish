import { Pool, type PoolClient } from 'pg';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { randomBytes } from 'node:crypto';

export const dataDir = process.env.DATA_DIR || join(process.cwd(), 'data');
const pool = new Pool({ connectionString: process.env.DATABASE_URL, max: 10 });
type Param = string | number | null;
type Row = Record<string, any>;
let initialization: Promise<void> | undefined;

const schema = `
CREATE TABLE IF NOT EXISTS classes(id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT NOT NULL, level TEXT NOT NULL, fee INTEGER NOT NULL CHECK(fee>=0), color TEXT NOT NULL DEFAULT 'green');
CREATE TABLE IF NOT EXISTS students(id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,name TEXT NOT NULL,parent TEXT NOT NULL DEFAULT '',phone TEXT NOT NULL DEFAULT '',class_id INTEGER NOT NULL REFERENCES classes(id),token TEXT UNIQUE NOT NULL);
CREATE TABLE IF NOT EXISTS sessions(id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,class_id INTEGER NOT NULL REFERENCES classes(id),date TEXT NOT NULL,time TEXT NOT NULL,duration INTEGER NOT NULL DEFAULT 90,topic TEXT NOT NULL DEFAULT '');
CREATE TABLE IF NOT EXISTS attendance(session_id INTEGER REFERENCES sessions(id),student_id INTEGER REFERENCES students(id),status TEXT NOT NULL,focus INTEGER NOT NULL DEFAULT 3,homework INTEGER NOT NULL DEFAULT 3,note TEXT NOT NULL DEFAULT '',PRIMARY KEY(session_id,student_id));
CREATE TABLE IF NOT EXISTS assignments(id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,class_id INTEGER NOT NULL REFERENCES classes(id),title TEXT NOT NULL,instructions TEXT NOT NULL,deadline TEXT NOT NULL,file_id TEXT);
CREATE TABLE IF NOT EXISTS submissions(id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,assignment_id INTEGER NOT NULL REFERENCES assignments(id),student_id INTEGER NOT NULL REFERENCES students(id),answer TEXT NOT NULL,file_id TEXT,submitted_at TEXT NOT NULL,feedback TEXT NOT NULL DEFAULT '',UNIQUE(assignment_id,student_id));
CREATE TABLE IF NOT EXISTS payments(id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,student_id INTEGER NOT NULL REFERENCES students(id),month TEXT NOT NULL,amount INTEGER NOT NULL CHECK(amount>=0),UNIQUE(student_id,month));
CREATE TABLE IF NOT EXISTS files(id TEXT PRIMARY KEY,name TEXT NOT NULL,type TEXT NOT NULL,size INTEGER NOT NULL,owner_token TEXT);
CREATE TABLE IF NOT EXISTS settings(key TEXT PRIMARY KEY,value TEXT NOT NULL);`;

function statement(sql: string) {
  let index = 0;
  return sql.replace(/\?/g, () => `$${++index}`);
}

async function seed(client: PoolClient) {
  if (process.env.SEED_DEMO_DATA !== 'true') return;
  const existing = await client.query('SELECT id FROM classes LIMIT 1');
  if (existing.rowCount) return;
  const classes = [
    ['Starters A1', 'Cambridge Starters', 150000, 'green'],
    ['Movers B1', 'Cambridge Movers', 180000, 'purple'],
    ['Flyers A2', 'Cambridge Flyers', 200000, 'orange'],
  ];
  const ids: number[] = [];
  for (const row of classes) {
    const result = await client.query('INSERT INTO classes(name,level,fee,color) VALUES($1,$2,$3,$4) RETURNING id', row);
    ids.push(result.rows[0].id);
  }
  const names = ['Nguyễn Minh Anh','Trần Gia Hân','Lê Bảo Ngọc','Phạm Đức Anh','Hoàng Nhật Minh','Võ Khánh Linh','Đặng Tuấn Kiệt','Bùi Phương Anh','Ngô Hải Đăng'];
  for (const [i, name] of names.entries()) {
    await client.query('INSERT INTO students(name,parent,phone,class_id,token) VALUES($1,$2,$3,$4,$5)', [name, 'Phụ huynh '+name.split(' ').slice(-2).join(' '), '', ids[Math.floor(i/3)], randomBytes(24).toString('hex')]);
  }
  const today = new Date().toLocaleDateString('en-CA',{timeZone:'Asia/Bangkok'});
  for (let d=0; d<7; d++) {
    const date = new Date(today+'T12:00:00+07:00');
    date.setUTCDate(date.getUTCDate()+d);
    await client.query('INSERT INTO sessions(class_id,date,time,duration,topic) VALUES($1,$2,$3,$4,$5)', [ids[d%3], date.toISOString().slice(0,10), d%2?'18:00':'17:00', 90, ['My family & friends','Let’s talk about animals','A day at school'][d%3]]);
  }
  await client.query('INSERT INTO assignments(class_id,title,instructions,deadline) VALUES($1,$2,$3,$4)', [ids[0], 'Unit 4 · My family', 'Viết 5 câu giới thiệu các thành viên trong gia đình bằng tiếng Anh.', today]);
}

async function initialize() {
  if (!process.env.DATABASE_URL) throw new Error('DATABASE_URL is required');
  const client = await pool.connect();
  try {
    await client.query('BEGIN');
    await client.query('SELECT pg_advisory_xact_lock(823761426)');
    await client.query(schema);
    await seed(client);
    await client.query('COMMIT');
  } catch (error) {
    await client.query('ROLLBACK');
    throw error;
  } finally {
    client.release();
  }
}

function ready() {
  initialization ??= initialize().catch(error => { initialization = undefined; throw error; });
  return initialization;
}

export async function all(sql: string, ...params: Param[]): Promise<Row[]> {
  await ready();
  return (await pool.query(statement(sql), params)).rows;
}
export async function get(sql: string, ...params: Param[]): Promise<Row | undefined> {
  return (await all(sql, ...params))[0];
}
export async function run(sql: string, ...params: Param[]) {
  await ready();
  return pool.query(statement(sql), params);
}
export async function transaction(action: (client: { run: typeof run }) => Promise<void>) {
  await ready();
  const client = await pool.connect();
  try {
    await client.query('BEGIN');
    await action({ run: (sql, ...params) => client.query(statement(sql), params) });
    await client.query('COMMIT');
  } catch (error) {
    await client.query('ROLLBACK');
    throw error;
  } finally {
    client.release();
  }
}
export async function snapshot() {
  const [classes, students, sessions, attendance, assignments, submissions, payments, settings] = await Promise.all([
    all('SELECT * FROM classes'), all('SELECT * FROM students'), all('SELECT * FROM sessions ORDER BY date,time'),
    all('SELECT * FROM attendance'), all('SELECT * FROM assignments ORDER BY deadline DESC'),
    all('SELECT * FROM submissions'), all('SELECT * FROM payments'),
    get("SELECT value FROM settings WHERE key='templates'"),
  ]);
  return { classes, students, sessions, attendance, assignments, submissions, payments,
    templates: JSON.parse(String(settings?.value || '["Con tập trung tốt và tích cực phát biểu.","Con cần ôn lại từ vựng và hoàn thành bài tập trước buổi học.","Con có nhiều tiến bộ, hãy tiếp tục phát huy nhé!"]')) };
}

function localSessionSecret() {
  mkdirSync(dataDir, { recursive: true });
  const path = join(dataDir, '.session-secret');
  try { writeFileSync(path, randomBytes(48).toString('hex'), { mode: 0o600, flag: 'wx' }); }
  catch (error) { if ((error as NodeJS.ErrnoException).code !== 'EEXIST') throw error; }
  return readFileSync(path, 'utf8');
}
export const sessionSecret = process.env.SESSION_SECRET || localSessionSecret();

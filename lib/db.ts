async function initialize() {
  if (!process.env.DATABASE_URL) throw new Error('DATABASE_URL is required');
  const client = await pool.connect();
  try {
    await client.query('BEGIN');
    await client.query('SELECT pg_advisory_xact_lock(823761426)');
    await client.query(schema);
    await seed(client);
    await backfillUsernames(client);
    await client.query('COMMIT');
  } catch (error) {
    await client.query('ROLLBACK');
    throw error;
  } finally {
    client.release();
  }
}

function ready() {
  initialization ??= initialize().catch(error => {
    initialization = undefined;
    throw error;
  });
  return initialization;
}

export async function all(sql: string, ...params: Param[]): Promise<Row[]> {
  await ready();
  return (await pool.query(statement(sql), params)).rows;
}
export async function get(sql: string, ...params: Param[]): Promise<Row | undefined> {
  return (await all(sql, ...params))[0];
}
export async function run(sql: string, ...params: Param[]) {
  await ready();
  return pool.query(statement(sql), params);
}
export async function transaction(action: (client: { run: typeof run }) => Promise<void>) {
  await ready();
  const client = await pool.connect();
  try {
    await client.query('BEGIN');
    await action({ run: (sql, ...params) => client.query(statement(sql), params) });
    await client.query('COMMIT');
  } catch (error) {
    await client.query('ROLLBACK');
    throw error;
  } finally {
    client.release();
  }
}
export async function snapshot() {
  const [classes, students, sessions, attendance, assignments, submissions, payments, templateSetting, bankSetting, fileRows] =
    await Promise.all([
      all('SELECT * FROM classes ORDER BY id'),
      all(`SELECT s.id, s.name, s.parent, s.phone, s.class_id, s.token, s.username,
                  (s.password_hash IS NOT NULL AND s.password_hash <> '') AS has_password,
                  COALESCE(p.cnt, 0)::int AS push_count
           FROM students s
           LEFT JOIN (SELECT student_id, COUNT(*) AS cnt FROM push_subscriptions GROUP BY student_id) p
             ON p.student_id = s.id
           ORDER BY s.id`),
      all('SELECT * FROM sessions ORDER BY date,time'),
      all('SELECT * FROM attendance'),
      all('SELECT * FROM assignments ORDER BY deadline DESC, id DESC'),
      all('SELECT * FROM submissions'),
      all('SELECT * FROM payments'),
      get("SELECT value FROM settings WHERE key='templates'"),
      get("SELECT value FROM settings WHERE key='bank'"),
      all('SELECT id, name, type FROM files'),
    ]);

  const fileMap = new Map<string, { name: string; type: string }>(
    fileRows.map(f => [String(f.id), { name: String(f.name), type: String(f.type) }]),
  );

  const normalizedAssignments = assignments.map(a => ({
    ...a,
    questions: parseJsonSafe<QuizQuestion[]>(a.questions, []),
  }));

  const normalizedSubmissions = submissions.map(sub => {
    const parsedAtts = parseJsonSafe<SubmissionAttachment[]>(sub.attachments, []);
    const attachments =
      parsedAtts.length > 0
        ? parsedAtts
        : sub.file_id
          ? [
              {
                id: String(sub.file_id),
                name: fileMap.get(String(sub.file_id))?.name || 'Tệp bài làm',
                type: fileMap.get(String(sub.file_id))?.type || '',
              },
            ]
          : [];
    return {
      ...sub,
      attachments,
      quiz_answers: parseJsonSafe<Record<string, number>>(sub.quiz_answers, {}),
      score: sub.score ? String(sub.score) : '',
      status: (sub.status ? String(sub.status) : 'submitted') as 'submitted' | 'reviewed' | 'needs_revision',
    };
  });

  const bank = parseJsonSafe<BankConfig>(bankSetting?.value, {
    bankId: '',
    accountNo: '',
    accountName: '',
  });

  return {
    classes,
    students,
    sessions,
    attendance,
    assignments: normalizedAssignments,
    submissions: normalizedSubmissions,
    payments,
    templates: parseJsonSafe<string[]>(
      templateSetting?.value,
      [
        'Con tập trung tốt và tích cực phát biểu.',
        'Con cần ôn lại từ vựng và hoàn thành bài tập trước buổi học.',
        'Con có nhiều tiến bộ, hãy tiếp tục phát huy nhé!',
      ],
    ),
    bank,
  };
}

function localSessionSecret() {
  mkdirSync(dataDir, { recursive: true });
  const path = join(dataDir, '.session-secret');
  try {
    writeFileSync(path, randomBytes(48).toString('hex'), { mode: 0o600, flag: 'wx' });
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code !== 'EEXIST') throw error;
  }
  return readFileSync(path, 'utf8');
}
export const sessionSecret = process.env.SESSION_SECRET || localSessionSecret();

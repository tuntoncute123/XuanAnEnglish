export function parseJsonSafe<T>(raw: unknown, fallback: T): T {
  if (raw === null || raw === undefined || raw === '') return fallback;
  if (typeof raw !== 'string') return raw as T;
  try {
    return JSON.parse(raw) as T;
  } catch {
    return fallback;
  }
}

function statement(sql: string) {
  let index = 0;
  return sql.replace(/\?/g, () => `$${++index}`);
}

export async function findUniqueUsername(
  desiredOrName: string,
  excludeStudentId?: number,
  queryFn: (sql: string, params: Param[]) => Promise<Row[]> = async (sql, params) =>
    (await pool.query(statement(sql), params)).rows,
): Promise<string> {
  let base = normalizeUsername(desiredOrName);
  if (base.length < 3) base = `${base || 'hs'}01`;
  base = base.slice(0, 30);
  let candidate = base;
  let suffix = 1;
  while (true) {
    const rows = excludeStudentId
      ? await queryFn('SELECT id FROM students WHERE LOWER(username)=? AND id<>? LIMIT 1', [candidate, excludeStudentId])
      : await queryFn('SELECT id FROM students WHERE LOWER(username)=? LIMIT 1', [candidate]);
    if (!rows.length) return candidate;
    suffix++;
    candidate = `${base.slice(0, 24)}${suffix}`;
  }
}

async function backfillUsernames(client: PoolClient) {
  const missing = (await client.query("SELECT id, name FROM students WHERE username IS NULL OR username = '' ORDER BY id")).rows;
  for (const row of missing) {
    const username = await findUniqueUsername(
      suggestUsername(String(row.name), Number(row.id)),
      Number(row.id),
      async (sql, params) => (await client.query(statement(sql), params)).rows,
    );
    await client.query('UPDATE students SET username=$1 WHERE id=$2', [username, row.id]);
  }
}

